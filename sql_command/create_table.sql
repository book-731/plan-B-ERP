-- ============================================================
-- 1. 使用者與權限管理模組
-- ============================================================

CREATE TABLE roles ( -- 角色表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE permissions ( -- 權限表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    module VARCHAR(50) NOT NULL
);

CREATE TABLE role_permissions ( -- 角色與權限關聯表
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE employees ( -- 員工表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_no VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(30),
    job_title VARCHAR(50) NOT NULL,
    hire_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT '在職' CHECK (status IN ('在職', '留職停薪', '離職'))
);

CREATE TABLE users ( -- 系統使用者表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT UNIQUE REFERENCES employees(id) ON DELETE SET NULL,
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- 2. 員工與排班管理模組
-- ============================================================

CREATE TABLE shifts ( -- 班別表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL
);

CREATE TABLE schedules ( -- 排班表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    shift_id BIGINT NOT NULL REFERENCES shifts(id) ON DELETE RESTRICT,
    work_date DATE NOT NULL,
    UNIQUE (employee_id, shift_id, work_date)
);

CREATE TABLE attendances ( -- 考勤表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    schedule_id BIGINT REFERENCES schedules(id) ON DELETE SET NULL,
    clock_in TIMESTAMPTZ NOT NULL,
    clock_out TIMESTAMPTZ CHECK (clock_out > clock_in),
    status VARCHAR(20) NOT NULL DEFAULT '正常' CHECK (status IN ('正常', '遲到', '早退', '缺勤', '加班'))
);

CREATE TABLE leave_requests ( -- 請假申請表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
    approver_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    leave_type VARCHAR(20) NOT NULL CHECK (leave_type IN ('事假', '病假', '特休', '公假', '喪假', '其他')),
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    reason TEXT,
    status VARCHAR(20) NOT NULL DEFAULT '待審核' CHECK (status IN ('待審核', '已核准', '已駁回')),
    CHECK (end_time > start_time)
);

-- ============================================================
-- 3. 菜單與商品管理模組
-- ============================================================

CREATE TABLE categories ( -- 菜單分類表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    sort_order INT NOT NULL DEFAULT 0
);

CREATE TABLE menu_items ( -- 菜單項目表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
    name VARCHAR(100) NOT NULL,
    price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
    image_url TEXT,
    is_combo BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT '上架' CHECK (status IN ('上架', '停售', '下架'))
);

CREATE TABLE combo_items ( -- 套餐項目表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combo_item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE CASCADE,
    included_item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE RESTRICT,
    quantity INT NOT NULL DEFAULT 1 CHECK (quantity > 0),
    UNIQUE (combo_item_id, included_item_id),
    CHECK (combo_item_id <> included_item_id)
);

CREATE TABLE materials ( -- 原材料表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    category VARCHAR(20) NOT NULL CHECK (category IN ('食材', '飲料', '包材')),
    unit VARCHAR(20) NOT NULL,
    current_stock NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
    safety_stock NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (safety_stock >= 0)
);

CREATE TABLE customization_groups ( -- 客製化組別表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    is_required BOOLEAN NOT NULL DEFAULT FALSE,
    max_selections INT NOT NULL DEFAULT 1 CHECK (max_selections > 0)
);

CREATE TABLE menu_item_customization_groups ( -- 菜單項目與客製化組別關聯表
    menu_item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES customization_groups(id) ON DELETE CASCADE,
    PRIMARY KEY (menu_item_id, group_id)
);

CREATE TABLE customization_options ( -- 客製化選項表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES customization_groups(id) ON DELETE CASCADE,
    material_id BIGINT REFERENCES materials(id) ON DELETE SET NULL,
    name VARCHAR(50) NOT NULL,
    extra_price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (extra_price >= 0),
    consume_qty NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (consume_qty >= 0)
);

-- ============================================================
-- 4. 訂單與銷售管理模組
-- ============================================================

CREATE TABLE orders ( -- 訂單表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(40) NOT NULL UNIQUE,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    order_type VARCHAR(20) NOT NULL CHECK (order_type IN ('內用', '外帶', '外送')),
    table_no VARCHAR(20),
    status VARCHAR(20) NOT NULL DEFAULT '待處理' CHECK (status IN ('待處理', '製作中', '已完成', '已取消')),
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    service_fee NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (service_fee >= 0),
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE order_items ( -- 訂單項目表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    menu_item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE RESTRICT,
    quantity INT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE order_item_customizations ( -- 訂單項目客製化表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL REFERENCES order_items(id) ON DELETE CASCADE,
    option_id BIGINT NOT NULL REFERENCES customization_options(id) ON DELETE RESTRICT,
    extra_price NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (extra_price >= 0)
);

CREATE TABLE payments ( -- 訂單付款表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE RESTRICT,
    payment_method VARCHAR(30) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
    paid_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============================================================
-- 5. 庫存管理與採購供應商模組
-- ============================================================

CREATE TABLE menu_item_recipes ( -- 菜單項目配方表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT NOT NULL REFERENCES menu_items(id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES materials(id) ON DELETE RESTRICT,
    quantity NUMERIC(12, 3) NOT NULL CHECK (quantity > 0),
    UNIQUE (menu_item_id, material_id)
);

CREATE TABLE suppliers ( -- 供應商表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    contact_person VARCHAR(50),
    phone VARCHAR(30),
    tax_id VARCHAR(20),
    payment_terms VARCHAR(100)
);

CREATE TABLE purchase_orders ( -- 採購訂單表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_no VARCHAR(40) NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
    applicant_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    expected_date DATE CHECK (expected_date >= order_date OR expected_date IS NULL),
    total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    status VARCHAR(20) NOT NULL DEFAULT '草稿' CHECK (status IN ('草稿', '已下單', '部分驗收', '已驗收', '已取消'))
);

CREATE TABLE purchase_order_items ( -- 採購訂單項目表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    material_id BIGINT NOT NULL REFERENCES materials(id) ON DELETE RESTRICT,
    ordered_qty NUMERIC(12, 3) NOT NULL CHECK (ordered_qty > 0),
    received_qty NUMERIC(12, 3) NOT NULL DEFAULT 0 CHECK (received_qty >= 0 AND received_qty <= ordered_qty),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    UNIQUE (purchase_order_id, material_id)
);

CREATE TABLE inventory_transactions ( -- 庫存交易紀錄表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES materials(id) ON DELETE RESTRICT,
    order_id BIGINT REFERENCES orders(id) ON DELETE RESTRICT,
    purchase_order_id BIGINT REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    transaction_type VARCHAR(20) NOT NULL CHECK (transaction_type IN ('進貨', '領料', '耗損', '調整', '銷售扣庫', '取消回補')),
    change_qty NUMERIC(12, 3) NOT NULL CHECK (change_qty <> 0),
    after_qty NUMERIC(12, 3) NOT NULL CHECK (after_qty >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (
            transaction_type IN ('銷售扣庫', '取消回補')
            AND order_id IS NOT NULL
            AND purchase_order_id IS NULL
        )
        OR (
            transaction_type = '進貨'
            AND order_id IS NULL
            AND purchase_order_id IS NOT NULL
        )
        OR (
            transaction_type IN ('領料', '耗損', '調整')
            AND order_id IS NULL
            AND purchase_order_id IS NULL
        )
    ),
    CHECK (
        (transaction_type IN ('進貨', '取消回補') AND change_qty > 0)
        OR (transaction_type IN ('領料', '耗損', '銷售扣庫') AND change_qty < 0)
        OR transaction_type = '調整'
    )
);

-- ============================================================
-- 6. 系統基礎設施模組（API 冪等性防重複送出）
-- ============================================================

CREATE TABLE idempotency_keys ( -- API 冪等性紀錄表
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_key VARCHAR(100) NOT NULL,
    http_method VARCHAR(10) NOT NULL,
    request_path VARCHAR(255) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PROCESSING'
        CHECK (status IN ('PROCESSING', 'COMPLETED', 'FAILED')),
    retryable BOOLEAN NOT NULL DEFAULT FALSE,
    response_status INT
        CHECK (response_status IS NULL OR response_status BETWEEN 100 AND 599),
    response_body JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '24 hours'),
    UNIQUE (actor_key, http_method, request_path, idempotency_key)
);

-- ============================================================
-- 7. 效能索引（支援營運報表、查詢與定期清理）
-- ============================================================

CREATE INDEX idx_schedules_work_date ON schedules(work_date);
CREATE INDEX idx_attendances_employee_clock_in ON attendances(employee_id, clock_in);
CREATE INDEX idx_menu_items_category_status ON menu_items(category_id, status);
CREATE INDEX idx_orders_created_at_status ON orders(created_at, status);
CREATE INDEX idx_order_items_order_id ON order_items(order_id);
CREATE INDEX idx_order_items_menu_item_id ON order_items(menu_item_id);
CREATE INDEX idx_payments_order_id ON payments(order_id);
CREATE INDEX idx_purchase_orders_supplier_date ON purchase_orders(supplier_id, order_date);
CREATE INDEX idx_inventory_tx_material_created ON inventory_transactions(material_id, created_at);
CREATE INDEX idx_idempotency_keys_created_at ON idempotency_keys(created_at);
CREATE INDEX idx_idempotency_keys_expires_at ON idempotency_keys(expires_at);
